import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "msedge", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on("console", (m) => logs.push(`${m.type()}: ${m.text()}`));
page.on("pageerror", (e) => logs.push(`PAGEERROR: ${e.message}`));
await page.goto("http://localhost:5199/?edit=1");
await page.waitForFunction(() => window.__worldEditor, null, { timeout: 90000 });
const out = {};
out.counts = await page.evaluate(() => { const l = window.__worldEditor.list(); return { towers: l.towers.length, lamps: l.lamps.length, props: l.props.length, models: window.__worldEditor.models().length }; });
await page.waitForTimeout(1500);
await page.screenshot({ path: "artifacts/evidence/world-editor-017/editor-1.png" });
out.sel = await page.evaluate(() => { const e = window.__worldEditor; const t = e.list().towers[3]; e.select("tower", t.id); e.focus(); e.patch({ dx: 12, dry: 0.5, hs: 1.5 }); return { id: t.id, selected: e.selected() }; });
await page.waitForTimeout(1500);
await page.screenshot({ path: "artifacts/evidence/world-editor-017/editor-2.png" });
out.prop = await page.evaluate(async () => { const e = window.__worldEditor; await e.addProp("truck.glb"); return e.selected(); });
await page.waitForTimeout(1500);
await page.screenshot({ path: "artifacts/evidence/world-editor-017/editor-3.png" });
out.json = await page.evaluate(() => window.__worldEditor.json());
console.log(JSON.stringify(out, null, 1));
console.log(logs.filter((l) => !/vite|DevTools/.test(l)).slice(0, 15).join("\n"));
await browser.close();
