import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "msedge", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } });
const errors = [];
page.on("pageerror", (e) => /Hydration/.test(e.message) || errors.push(e.message));
await page.goto("http://localhost:5199/atelier.html");
await page.click("#tab-world");
await page.waitForFunction(() => document.querySelector("#world-status")?.textContent?.startsWith("ready"), null, { timeout: 120000 });
const out = {};
out.towerButtons = await page.locator("#world-list button").count();
await page.click('[data-wk="lamp"]');
out.lampButtons = await page.locator("#world-list button").count();
await page.fill("#world-filter", "l1");
out.filtered = await page.locator("#world-list button").count();
await page.locator("#world-list button").first().click();
await page.waitForTimeout(1200);
out.sel = await page.textContent("#world-sel");
out.sliders = await page.locator("#world-fields input").count();
const slider = page.locator('#world-fields input[data-wf="dx"]');
await slider.evaluate((el) => { el.value = String(Number(el.value) + 5); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); });
await page.waitForTimeout(500);
out.afterSlider = await page.evaluate(() => document.querySelector("#world")?.contentWindow.__worldEditor.selected().item);
await page.click("#w-hide");
out.afterHide = await page.evaluate(() => document.querySelector("#world")?.contentWindow.__worldEditor.selected().item);
await page.click("#w-reset");
out.afterReset = await page.evaluate(() => document.querySelector("#world")?.contentWindow.__worldEditor.selected().item ?? null);
await page.click("#w-turn"); await page.click("#w-move");
await page.click("#w-add");
await page.waitForTimeout(1500);
out.afterAdd = await page.textContent("#world-sel");
await page.click("#w-del");
out.afterDel = await page.textContent("#world-sel");
await page.screenshot({ path: "artifacts/evidence/world-editor-017/panel.png" });
console.log(JSON.stringify(out, null, 1), "errors:", errors);
await browser.close();
