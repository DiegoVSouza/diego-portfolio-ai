import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "msedge", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } });
const errors = []; page.on("pageerror", (e) => /Hydration/.test(e.message) || errors.push(e.message));
await page.goto("http://localhost:5199/atelier.html");
await page.click("#tab-world");
await page.waitForFunction(() => document.querySelector("#world-status")?.textContent?.startsWith("ready"), null, { timeout: 120000 });
await page.waitForTimeout(1500);
await page.click('[data-wk="board"]');
const out = { boards: await page.locator("#world-list button").count() };
await page.locator("#world-list button").nth(2).click();
await page.waitForTimeout(1500);
out.sliders = await page.locator("#world-fields input").count();
const ed = (fn) => page.evaluate(fn);
out.before = await ed(() => document.querySelector("#world").contentWindow.__worldEditor.selected().shot);
await page.screenshot({ path: "artifacts/evidence/world-editor-017/board-before.png" });
await page.locator('#world-fields input[data-wf="bottom"]').evaluate((el) => { el.value = String(Number(el.value) + 6); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); });
out.after = await ed(() => document.querySelector("#world").contentWindow.__worldEditor.selected().shot);
await page.click("#w-save");
await page.waitForTimeout(6000);
await page.waitForFunction(() => document.querySelector("#world-status")?.textContent?.startsWith("ready"), null, { timeout: 120000 });
await page.waitForTimeout(2500);
out.reloaded = await ed(() => { const e = document.querySelector("#world").contentWindow.__worldEditor; e.select("board", "b2"); return e.selected().shot; });
await page.waitForTimeout(1500);
await page.screenshot({ path: "artifacts/evidence/world-editor-017/board-after.png" });
console.log(JSON.stringify(out), errors);
await browser.close();
